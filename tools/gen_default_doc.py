#!/usr/bin/env python3
"""Generate src/default_doc.js from samples/demo.md.

The shipped default buffer and the visual test fixture are the same document, so
it lives in exactly one place — `samples/demo.md` — and this turns it into the
one-global JS file the build concatenates. `build.py` calls `generate()` on every
run, which is what stops the two from drifting.

The escaping is the whole job. Inside a JS template literal:

  * a backslash starts an escape sequence, so raw `\\pi` would evaluate to `pi`
    and silently strip every TeX command in the document. Backslashes double.
  * a backtick ends the literal.
  * `${` opens an interpolation.

Order matters: double the backslashes first, then guard backticks and `${`, so
the guards' own backslashes are not doubled in turn.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "samples" / "demo.md"
TARGET = ROOT / "src" / "default_doc.js"

HEADER = """\
/* default_doc.js — GENERATED by tools/gen_default_doc.py. Do not edit.
 *
 * Source of truth: samples/demo.md
 * Regenerate with: python3 tools/gen_default_doc.py  (build.py does it for you)
 *
 * The document the editor opens with when localStorage holds no buffer. One
 * global, no side effects, so it can be loaded before app.js and read under
 * node by tests/load.mjs.
 */
(function () {
  'use strict';
  var DOC = `"""

FOOTER = """`;

  var root = (typeof window !== 'undefined')
    ? window
    : (typeof globalThis !== 'undefined' ? globalThis : this);
  root.DEFAULT_DOC = DOC;
})();
"""


def escape_template_literal(text: str) -> str:
    """Make `text` safe to sit inside a JS backtick literal, byte for byte."""
    out = text.replace("\\", "\\\\")
    out = out.replace("`", "\\`")
    out = out.replace("${", "\\${")
    return out


def render(text: str) -> str:
    # A trailing newline inside the literal is meaningful; normalise to exactly
    # one so the generated file is stable no matter how the .md was saved.
    body = text.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n") + "\n"
    return HEADER + escape_template_literal(body) + FOOTER


def generate(quiet: bool = False) -> Path:
    if not SOURCE.exists():
        raise SystemExit(f"gen_default_doc: missing {SOURCE}")
    js = render(SOURCE.read_text(encoding="utf-8"))
    # Only write when it changed, so a build does not churn the file's mtime.
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if old != js:
        TARGET.write_text(js, encoding="utf-8")
        if not quiet:
            print(f"gen_default_doc: wrote {TARGET.name} from {SOURCE.name}")
    elif not quiet:
        print(f"gen_default_doc: {TARGET.name} already current")
    return TARGET


def main() -> int:
    generate()
    return 0


if __name__ == "__main__":
    sys.exit(main())
